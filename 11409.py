import sys, heapq
from collections import deque
input_ = sys.stdin.readline
def minput(): return map(int, input_().split())


class MCMFEdge:
    def __init__(self, start, end, capacity, cost):
        self.start = start
        self.end = end
        self.capacity = capacity
        self.cost = cost
        self.flow = 0
        self.reverse = None

    def __repr__(self):
        return f"({self.end}, cap: {self.capacity}, flow: {self.flow}, cost: {self.cost})"


def add_edge_mcmf(graph, start, end, capacity, cost):
    forward = MCMFEdge(start, end, capacity, cost)
    backward = MCMFEdge(end, start, 0, -cost)
    forward.reverse = backward
    backward.reverse = forward
    graph[start].append(forward)
    graph[end].append(backward)


def MCMF(graph, source, sink):
    INF = float('inf')
    n = len(graph)

    potential = [INF] * n
    in_queue = [False] * n
    potential[source] = 0

    q = deque([source])
    in_queue[source] = True

    while q:
        u = q.popleft()
        in_queue[u] = False
        for edge in graph[u]:
            if edge.capacity > edge.flow and potential[u] + edge.cost < potential[edge.end]:
                potential[edge.end] = potential[u] + edge.cost
                if not in_queue[edge.end]:
                    in_queue[edge.end] = True
                    q.append(edge.end)

    flow = 0
    min_cost = 0

    while True:
        dist = [INF] * n
        parent = [(-1, None)] * n
        dist[source] = 0

        pq = [(0, source)]
        while pq:
            cur_dist, u = heapq.heappop(pq)
            if dist[u] < cur_dist:
                continue
            for edge in graph[u]:
                if edge.flow < edge.capacity:
                    cost_u_v = edge.cost + potential[u] - potential[edge.end]
                    nd = cur_dist + cost_u_v
                    if nd < dist[edge.end]:
                        dist[edge.end] = nd
                        parent[edge.end] = (u, edge)
                        heapq.heappush(pq, (nd, edge.end))

        if dist[sink] == INF:
            break

        for i in range(n):
            if dist[i] < INF:
                potential[i] += dist[i]

        increment_flow = INF
        v = sink
        while v != source:
            u, edge = parent[v]
            if u == -1:
                increment_flow = 0
                break
            increment_flow = min(increment_flow, edge.capacity - edge.flow)
            v = u

        if not increment_flow:
            break

        v = sink
        while v != source:
            u, edge = parent[v]
            edge.flow += increment_flow
            edge.reverse.flow -= increment_flow
            min_cost += edge.cost * increment_flow
            v = u

        flow += increment_flow

    return flow, min_cost


N, M = minput()
g = [[] for _ in range(N + M + 2)]

for i in range(1, N + 1):
    add_edge_mcmf(g, 0, i, 1, 0)

for i in range(1, N + 1):
    cnt, *works = minput()
    ptr = 0
    while ptr < len(works):
        work, cost = works[ptr], works[ptr + 1]
        add_edge_mcmf(g, i, work + N, 1000000, -cost)
        ptr += 2

for i in range(N + 1, N + M + 1):
    add_edge_mcmf(g, i, N + M + 1, 1, 0)

flow, cost = MCMF(g, 0, N + M + 1)
